"""Draws the weather icons and compiles them into src/icons.c (RGB565A8 images).

    python tools/make_icons.py

Needs Google Chrome (to render the SVGs) and Pillow.
"""
import os
import subprocess
import tempfile

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CHROME = r"C:\Program Files\Google\Chrome\Application\chrome.exe"
SIZES = {"large": 80, "small": 36}

SUN = '<circle cx="50" cy="50" r="19" fill="#FFC83D"/>' + "".join(
    f'<line x1="50" y1="22" x2="50" y2="10" stroke="#FFC83D" stroke-width="6" stroke-linecap="round" transform="rotate({a} 50 50)"/>'
    for a in range(0, 360, 45))
MOON = '<path d="M58,14 A34,34 0 1,0 86,62 A27,27 0 1,1 58,14 Z" fill="#E6E3F2"/>'
CLOUD = '<path d="M26,74 H74 A15,15 0 0,0 74,44 A23,23 0 0,0 31,38 A18,18 0 0,0 26,74 Z" fill="{c}"/>'


def cloud(color="#E9EEF5", dy=0):
    return f'<g transform="translate(0 {dy})">{CLOUD.format(c=color)}</g>'


def small(svg, x, y, s):
    return f'<g transform="translate({x} {y}) scale({s})">{svg}</g>'


ICONS = {
    "clear_day": SUN,
    "clear_night": MOON,
    "partly_day": small(SUN, -6, -8, 0.72) + cloud(dy=8),
    "partly_night": small(MOON, -4, -6, 0.68) + cloud(dy=8),
    "cloudy": small(cloud("#AEB7C4"), 18, -10, 0.7) + cloud(dy=4),
    "fog": cloud("#C9D0DA", -12) + "".join(
        f'<line x1="{20 + o}" y1="{y}" x2="{80 - o}" y2="{y}" stroke="#9AA4B2" stroke-width="6" stroke-linecap="round"/>'
        for y, o in ((72, 0), (84, 8), (96, 16))),
    "drizzle": cloud(dy=-12) + "".join(
        f'<line x1="{x}" y1="74" x2="{x - 3}" y2="84" stroke="#7FB8FF" stroke-width="5" stroke-linecap="round"/>'
        for x in (36, 52, 68)),
    "rain": cloud("#C9D0DA", -12) + "".join(
        f'<line x1="{x}" y1="70" x2="{x - 8}" y2="92" stroke="#3D8BFF" stroke-width="6" stroke-linecap="round"/>'
        for x in (36, 54, 72)),
    "snow": cloud(dy=-12) + "".join(
        f'<g transform="translate({x} {y})" stroke="#FFFFFF" stroke-width="4" stroke-linecap="round">'
        '<line x1="-6" y1="0" x2="6" y2="0"/><line x1="-3" y1="-5" x2="3" y2="5"/><line x1="-3" y1="5" x2="3" y2="-5"/></g>'
        for x, y in ((34, 80), (52, 90), (70, 80))),
    "storm": cloud("#8E99A8", -12) + '<path d="M54,62 L40,84 H52 L46,100 L66,74 H54 L60,62 Z" fill="#FFD23F"/>',
}


def render(svg_body, size, path):
    svg = f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 100 100">{svg_body}</svg>'
    with tempfile.TemporaryDirectory() as tmp:
        html = os.path.join(tmp, "i.html")
        with open(html, "w") as fh:
            fh.write(f'<!doctype html><html><body style="margin:0;background:transparent">{svg}</body></html>')
        subprocess.run([CHROME, "--headless=new", "--disable-gpu", "--hide-scrollbars", "--default-background-color=00000000",
                        f"--window-size={size},{size}", f"--screenshot={path}", "file:///" + html.replace("\\", "/")],
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=True)


def to_rgb565a8(img):
    img = img.convert("RGBA")
    rgb, alpha = bytearray(), bytearray()
    for r, g, b, a in img.get_flattened_data():
        v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        rgb += bytes((v & 255, v >> 8))
        alpha.append(a)
    return bytes(rgb + alpha)


def main():
    out_c = ['// Generated by tools/make_icons.py - do not edit', '#include "icons.h"', '']
    names = []
    with tempfile.TemporaryDirectory() as tmp:
        for name, body in ICONS.items():
            for sz_name, px in SIZES.items():
                png = os.path.join(tmp, f"{name}_{px}.png")
                render(body, px, png)
                data = to_rgb565a8(Image.open(png))
                sym = f"icon_{name}_{sz_name}"
                rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 24]) for i in range(0, len(data), 24)]
                out_c.append(f"static const uint8_t {sym}_data[] = {{\n  " + ",\n  ".join(rows) + "\n};")
                out_c.append(f"const lv_image_dsc_t {sym} = {{\n  .header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565A8, "
                             f".flags = 0, .w = {px}, .h = {px}, .stride = {px * 2}}},\n  .data_size = sizeof({sym}_data),\n  .data = {sym}_data,\n}};\n")
            names.append(name)
    with open(os.path.join(ROOT, "src", "icons.c"), "w", newline="\n") as fh:
        fh.write("\n".join(out_c))
    hdr = ['// Generated by tools/make_icons.py - do not edit', '#pragma once', '#include <lvgl.h>', '',
           '#ifdef __cplusplus', 'extern "C" {', '#endif']
    for n in names:
        hdr.append(f"extern const lv_image_dsc_t icon_{n}_large, icon_{n}_small;")
    hdr += ['#ifdef __cplusplus', '}', '#endif', '']
    with open(os.path.join(ROOT, "src", "icons.h"), "w", newline="\n") as fh:
        fh.write("\n".join(hdr))
    # contact sheet for checking the artwork
    sheet = Image.new("RGBA", (len(names) * 90, 130), (16, 24, 40, 255))
    with tempfile.TemporaryDirectory() as tmp:
        for i, n in enumerate(names):
            for sz_name, px in SIZES.items():
                p = os.path.join(tmp, f"{n}_{px}.png")
                render(ICONS[n], px, p)
                sheet.alpha_composite(Image.open(p).convert("RGBA"), (i * 90 + 5, 5 if px == 80 else 90))
    sheet.save(os.path.join(ROOT, "tools", "icons_preview.png"))
    print(f"wrote {len(names)} icons")


if __name__ == "__main__":
    main()
